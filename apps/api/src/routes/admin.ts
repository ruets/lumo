import { createAccountInvite } from "../auth/signup.js";
import {
	adminAssignHouseholdBody,
	adminHouseholdBody,
	adminHouseholdsView,
	adminHouseholdView,
	adminUpdateUserBody,
	adminUsersView,
	adminUserView,
	idParams,
	instanceSettingsView,
	oneTimeCodeView,
	potAdjustmentBody,
	potBalanceView,
	removeMembershipParams,
	updateInstanceSettingsBody,
} from "../schemas.js";
import {
	adjustPot,
	adminCreateHousehold,
	assignHousehold,
	deleteHousehold,
	deleteUser,
	listHouseholds,
	listUsers,
	removeFromHousehold,
	renameHousehold,
	updateUser,
} from "../services/accounts.js";
import { getSettings, updateSettings } from "../services/settings.js";
import { route } from "./define.js";

const admin = { scope: "account", superAdmin: true, tag: "Admin" } as const;

/** Instance administration. Super admins see accounts and households, never their content. */
export const adminRoutes = [
	route({
		...admin,
		method: "get",
		url: "/admin/users",
		summary: "All accounts with their household and status",
		response: adminUsersView,
		handler: ({ db }) => listUsers(db),
	}),
	route({
		...admin,
		method: "post",
		url: "/admin/account-invites",
		summary: "Invite someone to create an account (OIDC or local), with a one-time code",
		response: oneTimeCodeView,
		status: 201,
		idempotent: false,
		handler: ({ db, account, now }) => createAccountInvite(db, account.userId, now),
	}),
	route({
		...admin,
		method: "patch",
		url: "/admin/users/:id",
		summary: "Grant or remove the super admin role, disable or enable an account",
		params: idParams,
		body: adminUpdateUserBody,
		response: adminUserView,
		handler: ({ db, account, params, body }) => updateUser(db, account, params.id, body),
	}),
	route({
		...admin,
		method: "delete",
		url: "/admin/users/:id",
		summary: "Delete an account (credentials erased, history kept)",
		params: idParams,
		status: 204,
		handler: ({ db, account, params, now }) => deleteUser(db, account, params.id, now),
	}),
	route({
		...admin,
		method: "post",
		url: "/admin/users/:id/households",
		summary: "Put an account into a household",
		params: idParams,
		body: adminAssignHouseholdBody,
		response: adminUserView,
		handler: ({ db, params, body }) => assignHousehold(db, params.id, body),
	}),
	route({
		...admin,
		method: "delete",
		url: "/admin/users/:id/households/:householdId",
		summary: "Take an account out of a household, keeping the account",
		params: removeMembershipParams,
		status: 204,
		handler: ({ db, params }) => removeFromHousehold(db, params.id, params.householdId),
	}),
	route({
		...admin,
		method: "get",
		url: "/admin/households",
		summary: "All households with their member count",
		response: adminHouseholdsView,
		handler: ({ db }) => listHouseholds(db),
	}),
	route({
		...admin,
		method: "post",
		url: "/admin/households",
		summary: "Create an empty household",
		body: adminHouseholdBody,
		response: adminHouseholdView,
		status: 201,
		handler: ({ db, body }) => adminCreateHousehold(db, body.name),
	}),
	route({
		...admin,
		method: "patch",
		url: "/admin/households/:id",
		summary: "Rename a household",
		params: idParams,
		body: adminHouseholdBody,
		response: adminHouseholdView,
		handler: ({ db, params, body }) => renameHousehold(db, params.id, body.name),
	}),
	route({
		...admin,
		method: "delete",
		url: "/admin/households/:id",
		summary: "Delete an empty household",
		params: idParams,
		status: 204,
		handler: ({ db, params }) => deleteHousehold(db, params.id),
	}),
	route({
		...admin,
		method: "post",
		url: "/admin/households/:id/pot/adjustments",
		summary: "Adjust a household pot with an explanatory note",
		params: idParams,
		body: potAdjustmentBody,
		response: potBalanceView,
		status: 201,
		handler: ({ db, account, params, body, now }) => adjustPot(db, account, params.id, body, now),
	}),
	route({
		...admin,
		method: "get",
		url: "/admin/settings",
		summary: "Instance settings",
		response: instanceSettingsView,
		handler: ({ db }) => getSettings(db),
	}),
	route({
		...admin,
		method: "patch",
		url: "/admin/settings",
		summary: "Change the instance settings",
		body: updateInstanceSettingsBody,
		response: instanceSettingsView,
		handler: ({ db, body }) => updateSettings(db, body),
	}),
];
