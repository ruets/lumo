import { z } from "zod";
import {
	completeBody,
	completionResult,
	completionView,
	createItemBody,
	idParams,
	itemView,
	listItemsQuery,
	pendingQuery,
	todayQuery,
	todayView,
	updateItemBody,
} from "../schemas.js";
import {
	approveCompletion,
	createCompletion,
	listPending,
	rejectCompletion,
	undoCompletion,
} from "../services/completions.js";
import { archiveItem, createItem, listItems, updateItem } from "../services/items.js";
import { getToday } from "../services/progress.js";
import { route } from "./define.js";

export const itemRoutes = [
	route({
		method: "post",
		url: "/items",
		summary: "Créer une habitude ou une tâche",
		tag: "Éléments",
		body: createItemBody,
		response: itemView,
		status: 201,
		handler: ({ db, actor, body, now }) => createItem(db, actor, body, now),
	}),
	route({
		method: "get",
		url: "/items",
		summary: "Lister les éléments visibles",
		tag: "Éléments",
		query: listItemsQuery,
		response: z.object({ items: z.array(itemView) }),
		handler: ({ db, actor, query }) => ({ items: listItems(db, actor, query.includeArchived) }),
	}),
	route({
		method: "patch",
		url: "/items/:id",
		summary: "Modifier un élément",
		tag: "Éléments",
		params: idParams,
		body: updateItemBody,
		response: itemView,
		handler: ({ db, actor, params, body }) => updateItem(db, actor, params.id, body),
	}),
	route({
		method: "delete",
		url: "/items/:id",
		summary: "Archiver un élément",
		tag: "Éléments",
		params: idParams,
		status: 204,
		handler: ({ db, actor, params, now }) => archiveItem(db, actor, params.id, now),
	}),
	route({
		method: "get",
		url: "/today",
		summary: "Éléments dus ce jour avec leur avancement",
		tag: "Éléments",
		query: todayQuery,
		response: todayView,
		handler: ({ db, actor, query, now }) => getToday(db, actor, query.date, now),
	}),
	route({
		method: "post",
		url: "/items/:id/completions",
		summary: "Valider un élément (les pièces sont calculées par le serveur)",
		tag: "Validations",
		params: idParams,
		body: completeBody,
		response: completionResult,
		status: 201,
		handler: ({ db, actor, params, body, now }) => createCompletion(db, actor, params.id, body, now),
	}),
	route({
		method: "get",
		url: "/completions",
		summary: "Validations en attente d'accord (owner et adultes)",
		tag: "Validations",
		query: pendingQuery,
		response: z.object({ completions: z.array(completionView) }),
		handler: ({ db, actor }) => ({ completions: listPending(db, actor) }),
	}),
	route({
		method: "delete",
		url: "/completions/:id",
		summary: "Annuler une validation (contre-écriture au journal)",
		tag: "Validations",
		params: idParams,
		response: completionResult,
		handler: ({ db, actor, params, now }) => undoCompletion(db, actor, params.id, now),
	}),
	route({
		method: "post",
		url: "/completions/:id/approve",
		summary: "Approuver la validation d'un enfant",
		tag: "Validations",
		params: idParams,
		response: completionResult,
		handler: ({ db, actor, params, now }) => approveCompletion(db, actor, params.id, now),
	}),
	route({
		method: "post",
		url: "/completions/:id/reject",
		summary: "Rejeter la validation d'un enfant",
		tag: "Validations",
		params: idParams,
		response: completionResult,
		handler: ({ db, actor, params }) => rejectCompletion(db, actor, params.id),
	}),
];
