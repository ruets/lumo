export type MessageKey = keyof typeof fr;
export type Locale = "fr";

const dictionaries: Record<Locale, Record<MessageKey, string>> = { fr };

export function t(key: MessageKey, params: Record<string, string | number> = {}, locale: Locale = "fr"): string {
	const template = dictionaries[locale][key];
	return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

export * from "./format.js";

/** Message d'erreur lisible pour un code d'erreur de l'API (`code` du problème HTTP). */
export function errorMessage(code: string, fallback?: string): string {
	const key = `errors.${code}`;
	return key in fr ? t(key as MessageKey) : (fallback ?? t("errors.unknown"));
}
